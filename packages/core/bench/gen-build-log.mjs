#!/usr/bin/env node
/**
 * Regenerates `bench/corpus/build.log` — a cargo-style build log derived from this
 * repository's own `pnpm-lock.yaml`.
 *
 * Honesty label, stated here and in the log's first line: the package names and
 * versions are real (read from the committed lockfile), but no cargo build produced
 * this file — the `Compiling …` framing is synthetic. A real cargo log from someone
 * else's project would not be reproducible from this repository; this one is, by
 * running this script, which is the property the corpus needs. Deterministic: same
 * lockfile, byte-identical log.
 *
 * Zero dependencies, `node:` builtins only, no network.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const benchDir = dirname(fileURLToPath(import.meta.url));
const lockfile = resolve(benchDir, '../../../pnpm-lock.yaml');
const out = join(benchDir, 'corpus/build.log');

/** `  'name@1.2.3':` entries under the lockfile's `packages:` section. */
export function packagesFromLockfile(lockfileText) {
  const packages = [];
  for (const line of lockfileText.split('\n')) {
    const match = /^ {2}'(?<name>@?[^']+)@(?<version>[^@']+)':$/.exec(line);
    if (match?.groups) packages.push({ name: match.groups.name, version: match.groups.version });
  }
  return packages;
}

/** The log text, from the parsed package list. Pure, so a test can pin it. */
export function renderBuildLog(packages) {
  const lines = [
    '# synthetic cargo-style build log — generated by bench/gen-build-log.mjs from',
    '# this repository’s pnpm-lock.yaml. Package names and versions are real; the',
    '# cargo framing is not. See bench/README.md.',
    ...packages.map(({ name, version }) => `   Compiling ${name} v${version}`),
    `    Finished \`dev\` profile [unoptimized + debuginfo] target(s), ${String(packages.length)} units`,
  ];
  return `${lines.join('\n')}\n`;
}

// Generate only when executed directly — importing this module (the test does, to
// compare the committed log against a fresh render) must not write anything.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const packages = packagesFromLockfile(readFileSync(lockfile, 'utf8'));
  if (packages.length === 0) {
    throw new Error('gen-build-log: found no packages in pnpm-lock.yaml — the parse is broken.');
  }
  writeFileSync(out, renderBuildLog(packages));
  process.stderr.write(`gen-build-log: ${String(packages.length)} packages → ${out}\n`);
}
